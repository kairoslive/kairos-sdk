// Generates src/openapi/perps-*.ts from the perps paths of Kairos' OpenAPI specs.
//
// The perps surface ships on staging before the public docs publish it, so this reads the specs from a directory
// (for example `docs/api/` of a kairos checkout at the staging ref) or a base URL, keeps only the perps paths and
// the components they reference, and writes one types file per API:
//
//   node scripts/generate-perps-openapi.mjs file:///path/to/kairos/docs/api/
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import openapiTS, { astToString } from "openapi-typescript";

// openapi-typescript already ships Redocly's YAML parser; reuse it rather than adding a dependency.
const { parseYaml } = createRequire(createRequire(import.meta.url).resolve("openapi-typescript"))("@redocly/openapi-core");

const specs = [
  { name: "perps-execution", file: "execution.yaml", keep: (p) => p.startsWith("/perps/") },
  { name: "perps-market-data", file: "market-data-api.yaml", keep: (p) => p.startsWith("/v1/perpetuals/") },
  { name: "perps-data", file: "data-api.yaml", keep: (p) => p.startsWith("/perpetuals/") },
];

const base = process.argv[2];
if (!base) throw new Error("usage: generate-perps-openapi.mjs <spec directory URL, e.g. file:///…/kairos/docs/api/>");

for (const { name, file, keep } of specs) {
  const source = new URL(file, base);
  const spec = parseYaml(source.protocol === "file:" ? await readFile(source, "utf8") : await download(source));
  const pruned = prune(spec, keep);
  const ast = await openapiTS(pruned, { alphabetize: true, exportType: true });
  await writeFile(new URL(`../src/openapi/${name}.ts`, import.meta.url),
    `// Generated by scripts/generate-perps-openapi.mjs from the perps paths of Kairos' ${file}.\n` +
    astToString(ast, { formatOptions: { removeComments: true } }));
  console.log(`${name}: ${Object.keys(pruned.paths).length} paths, ${countComponents(pruned)} components`);
}

/** Keeps the matching paths and the transitive closure of the components they reference. */
function prune(spec, keep) {
  const paths = Object.fromEntries(Object.entries(spec.paths ?? {}).filter(([p]) => keep(p)));
  const components = {};
  const queue = [paths];
  const seen = new Set();
  while (queue.length) {
    const node = queue.pop();
    if (!node || typeof node !== "object") continue;
    if (typeof node.$ref === "string" && node.$ref.startsWith("#/components/") && !seen.has(node.$ref)) {
      seen.add(node.$ref);
      const [, , kind, key] = node.$ref.split("/");
      const target = spec.components?.[kind]?.[key];
      if (target === undefined) throw new Error(`Unresolved ${node.$ref}`);
      (components[kind] ??= {})[key] = target;
      queue.push(target);
    }
    for (const value of Object.values(node)) queue.push(value);
  }
  // Security schemes are referenced by name from `security`, not by $ref.
  if (spec.components?.securitySchemes) components.securitySchemes = spec.components.securitySchemes;
  return { openapi: spec.openapi, info: spec.info, servers: spec.servers, paths, components };
}

function countComponents(spec) {
  return Object.values(spec.components).reduce((n, group) => n + Object.keys(group).length, 0);
}

async function download(source) {
  const res = await fetch(source);
  if (!res.ok) throw new Error(`Failed to read ${source}: ${res.status}`);
  return res.text();
}
