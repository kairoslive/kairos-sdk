import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const specs = {
  data: "data-api.yaml",
  execution: "execution.yaml",
  "market-data": "market-data-api.yaml",
};

await Promise.all(Object.entries(specs).map(async ([name, file]) => {
  const source = new URL(file, process.argv[2] ?? "https://docs.kairos.trade/openapi/");
  const spec = source.protocol === "file:" ? await readFile(source, "utf8") : await download(source);
  const ast = await openapiTS(spec, { alphabetize: true, exportType: true });
  await writeFile(new URL(`../src/openapi/${name}.ts`, import.meta.url),
    `// Generated by scripts/generate-openapi.mjs from Kairos' ${file}.\n` +
    astToString(ast, { formatOptions: { removeComments: true } }));
}));

async function download(source) {
  const res = await fetch(source);
  if (!res.ok) throw new Error(`Failed to read ${source}: ${res.status}`);
  return res.text();
}
