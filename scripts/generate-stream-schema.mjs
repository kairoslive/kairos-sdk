import { writeFile } from "node:fs/promises";

const base = "https://assets.kairos.trade/proto/kairos/v1/";
const sources = [
  ...["common", "websocket_control", "orderbook", "trade", "candle", "price_update", "volume", "lvc", "tick_size", "sports"]
    .map((name) => `${base}${name}.proto`),
  "https://app.kairos.trade/proto/kairos/synthetic/v1/synthetic.proto",
  "https://docs.kairos.trade/websocket/enriched-trades.md",
];
const frames = [
  "OrderbookSnapshot", "OrderbookDelta", "OrderbookDeltaBatch", "Candle", "TradeBatch", "PriceUpdate", "Volume",
  "PongResponse", "SubscribedResponse", "UnsubscribedResponse", "ErrorResponse", "Quote", "TickSizeUpdate",
  "MarketResolvedNotice", "MarketResolutionUpdate", "EnrichedTradeBatch", "TradePnLBatch",
  "SportsGameUpdate", "SportsSnapshot", "SportsEventUpdate",
  "SyntheticSnapshot", "SyntheticDelta", "SyntheticQuote", "SyntheticTradeBatch",
];
const primitives = new Set(["int64", "uint64", "int32", "uint32", "bool", "double", "string", "bytes"]);
const fieldsPattern = /^\s*(?:(repeated|optional)\s+)?([\w.]+|map<string,\s*string>)\s+(\w+)\s*=\s*(\d+)(?:\s*\[.*\])?\s*$/;

async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Failed to read ${url}: ${response.status}`);
  const body = await response.text();
  if (!url.endsWith(".md")) return body;
  const fenced = body.match(/^> ```protobuf[^\n]*\n([\s\S]*?)^> ```/m)?.[1];
  if (!fenced) throw new Error(`Protobuf code block missing from ${url}`);
  return fenced.replace(/^> ?/gm, "");
}

function fields(body, enums) {
  return body.split(";").map((line) => line.trim()).filter((line) => line && !/^(?:reserved|option) /.test(line)).map((line) => {
    const match = fieldsPattern.exec(line);
    if (!match) throw new Error(`Unsupported protobuf declaration: ${line}`);
    const [, modifier, declaration, snake, number] = match;
    const key = snake.replace(/_([a-z0-9])/g, (_, letter) => letter.toUpperCase());
    const type = declaration.split(".").at(-1);
    if (declaration.startsWith("map<")) return [number, key, "stringMapEntry", "map"];
    return [number, key, enums.has(type) ? "uint32" : type, modifier];
  });
}

const source = (await Promise.all(sources.map(download))).join("\n").replace(/\/\/[^\n]*/g, "");
const enums = new Set(Array.from(source.matchAll(/enum\s+(\w+)\s*\{/g), (match) => match[1]));
const messages = new Map(Array.from(source.matchAll(/message\s+(\w+)\s*\{([^{}]*)\}/g), ([, name, body]) => [name, fields(body, enums)]));
messages.set("stringMapEntry", [["1", "key", "string"], ["2", "value", "string"]]);

const used = new Set();
function include(name) {
  if (primitives.has(name) || used.has(name)) return;
  const message = messages.get(name);
  if (!message) throw new Error(`Missing schema for ${name}`);
  used.add(name);
  for (const [, , type] of message) include(type);
}
frames.forEach(include);

const output = [
  "// Generated by scripts/generate-stream-schema.mjs from the published Kairos protobuf schemas.",
  "// https://docs.kairos.trade/websocket/protobuf-reference",
  "// https://docs.kairos.trade/websocket/enriched-trades#messages",
  "",
  "export const streamSchemas = {",
];
for (const [name, message] of messages) {
  if (!used.has(name)) continue;
  output.push(`  ${name}: {`);
  for (const [number, key, type, modifier] of message) {
    const suffix = modifier ? `, "${modifier}"` : "";
    output.push(`    ${number}: ["${key}", "${type}"${suffix}],`);
  }
  output.push("  },");
}
output.push("} as const;", "");
await writeFile(new URL("../src/stream-schema.ts", import.meta.url), output.join("\n"));
